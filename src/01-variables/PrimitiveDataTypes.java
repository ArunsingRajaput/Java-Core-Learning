public class PrimitiveDataTypes {

    public static void main(String[] args) {

        byte age = 21;

        short year = 2026;

        int salary = 25000;

        long population = 9876543210L;

        float percentage = 75.5f;

        double price = 999.99;

        char grade = 'A';

        boolean isPassed = true;

        System.out.println("Byte: " + age);
        System.out.println("Short: " + year);
        System.out.println("Integer: " + salary);
        System.out.println("Long: " + population);
        System.out.println("Float: " + percentage);
        System.out.println("Double: " + price);
        System.out.println("Character: " + grade);
        System.out.println("Boolean: " + isPassed);
    }
}